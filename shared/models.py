"""
SentinelOps AI - Shared Pydantic Data Models.
Agreed schemas across all 4 team members for Phase 1, Phase 2, and SaaS.
"""

from datetime import datetime, timezone
from typing import Optional, List, Any, Dict
from pydantic import BaseModel, Field, field_validator

from shared.constants import (
    SEVERITY_MEDIUM,
    INCIDENT_STATUS_OPEN,
)


class TelemetryPayload(BaseModel):
    """
    Standard agreed telemetry payload across all 4 team members.
    Matches Section 7 Shared Telemetry Schema.
    """
    payload_id: str = Field(
        ...,
        description="Unique identifier for the telemetry event for deduplication (e.g. evt_0001)",
        min_length=1,
    )
    tenant_id: str = Field(
        default="tenant_demo",
        description="Tenant identifier for multi-tenancy separation",
        min_length=1,
    )
    source_id: str = Field(
        ...,
        description="Pseudonymous host/node identifier (e.g. node_a81f)",
        min_length=1,
    )
    timestamp_utc: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat(),
        description="Event generation timestamp in UTC (ISO-8601)",
    )
    cpu: float = Field(
        ...,
        ge=0.0,
        le=100.0,
        description="CPU utilization percentage (0.0 - 100.0)",
    )
    memory: float = Field(
        ...,
        ge=0.0,
        le=100.0,
        description="Memory utilization percentage (0.0 - 100.0)",
    )
    disk: float = Field(
        ...,
        ge=0.0,
        le=100.0,
        description="Disk utilization percentage (0.0 - 100.0)",
    )
    latency_ms: float = Field(
        ...,
        ge=0.0,
        description="Network round-trip latency in milliseconds (>= 0.0)",
    )
    packet_loss_pct: float = Field(
        ...,
        ge=0.0,
        le=100.0,
        description="Network packet loss percentage (0.0 - 100.0)",
    )
    error_count: int = Field(
        default=0,
        ge=0,
        description="Count of system or application errors observed (>= 0)",
    )
    failed_logins: int = Field(
        default=0,
        ge=0,
        description="Number of failed authentication attempts (>= 0)",
    )
    collector_status: str = Field(
        default="online",
        description="Status of the local collector agent (e.g. 'online', 'degraded', 'offline')",
        min_length=1,
    )
    event_category: Optional[str] = Field(
        default="normal",
        description="Optional telemetry classification category (e.g. 'normal', 'resource_pressure')",
    )

    @field_validator("payload_id", "tenant_id", "source_id", "collector_status")
    @classmethod
    def validate_non_empty_strings(cls, v: str, info) -> str:
        if not v or not v.strip():
            raise ValueError(f"Field '{info.field_name}' must not be empty or whitespace only.")
        return v.strip()


class Alert(BaseModel):
    """
    Individual anomaly or threshold violation alert detected by anomaly.py.
    """
    id: str = Field(..., description="Unique alert identifier")
    alert_type: str = Field(..., description="Type of alert e.g. CPU_SPIKE, LATENCY_SPIKE")
    severity: str = Field(default=SEVERITY_MEDIUM, description="LOW, MEDIUM, HIGH, CRITICAL")
    source_id: str = Field(..., description="Pseudonymous source node identifier")
    tenant_id: str = Field(default="tenant_demo", description="Tenant separation identifier")
    payload_id: Optional[str] = Field(default=None, description="Linked telemetry payload ID")
    metric_name: Optional[str] = Field(default=None, description="Primary metric triggering alert")
    metric_value: Optional[float] = Field(default=None, description="Observed value")
    threshold: Optional[float] = Field(default=None, description="Threshold breached if applicable")
    evidence: str = Field(..., description="Human-readable explanation of the anomaly")
    detection_method: str = Field(..., description="threshold | statistical | isolation_forest")
    anomaly_score: float = Field(default=0.0, ge=0.0, le=1.0, description="Anomaly confidence / deviation score")
    timestamp: str = Field(..., description="UTC ISO timestamp of alert creation")
    status: str = Field(default="active", description="active | resolved")


class RootCauseHypothesis(BaseModel):
    """
    Explainable root cause deduction generated by root_cause.py.
    """
    scenario_id: str = Field(..., description="Canonical scenario identifier")
    possible_cause: str = Field(..., description="Human-readable probable cause statement")
    confidence: float = Field(default=0.8, ge=0.0, le=1.0, description="Confidence level of hypothesis")
    evidence: List[str] = Field(default_factory=list, description="List of concrete metric observations")
    contributing_symptoms: List[str] = Field(default_factory=list, description="Contributing symptom tags")


class Recommendation(BaseModel):
    """
    Actionable next-step recommendation generated by recommendations.py.
    """
    id: str = Field(..., description="Recommendation unique ID")
    incident_id: str = Field(..., description="Linked incident ID")
    priority: str = Field(default="P2", description="Priority level: P1 (Urgent), P2 (High), P3 (Medium)")
    action: str = Field(..., description="Short action summary")
    description: str = Field(..., description="Detailed step-by-step guidance")
    rationale: str = Field(..., description="Explanation of why this action is suggested")
    execution_type: str = Field(default="manual", description="Always manual/assisted, never unattended")


class Incident(BaseModel):
    """
    Correlated grouping of alerts representing a cohesive system event.
    """
    id: str = Field(..., description="Unique incident identifier")
    title: str = Field(..., description="Concise summary title")
    severity: str = Field(..., description="Overall incident severity: LOW, MEDIUM, HIGH, CRITICAL")
    affected_source: str = Field(..., description="Source node ID affected")
    tenant_id: str = Field(default="tenant_demo", description="Tenant isolation ID")
    alert_ids: List[str] = Field(default_factory=list, description="IDs of correlated alerts")
    alerts: List[Alert] = Field(default_factory=list, description="Full correlated alerts")
    root_cause_hint: Optional[str] = Field(default=None, description="Summary of likely root cause")
    root_cause_details: Optional[RootCauseHypothesis] = Field(default=None, description="Detailed hypothesis")
    recommendations: List[Recommendation] = Field(default_factory=list, description="Associated recommendations")
    evidence_summary: List[str] = Field(default_factory=list, description="Key combined evidence points")
    status: str = Field(default=INCIDENT_STATUS_OPEN, description="OPEN | INVESTIGATING | RESOLVED")
    created_at: str = Field(..., description="Timestamp incident opened (UTC)")
    updated_at: str = Field(..., description="Timestamp of latest correlated alert (UTC)")


class BasicAlert(BaseModel):
    """
    Alert record triggered when an abnormal threshold or rule is breached.
    Supports both Member 3 Dashboard and Member 1/4 Backend formats.
    """
    alert_id: str = Field(..., description="Unique alert ID (e.g. alt_xxxx)")
    source_id: str = Field(..., description="Affected infrastructure source / node")
    metric: str = Field(default="threshold", description="Metric that triggered the alert (e.g. cpu, memory)")
    current_value: float = Field(default=0.0, description="Observed metric value")
    threshold: float = Field(..., description="Threshold exceeded")
    severity: str = Field(..., description="Alert severity: WARNING, CRITICAL")
    message: str = Field(..., description="Human-readable explanation of the alert")
    timestamp_utc: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat(),
        description="Timestamp when the alert was triggered",
    )
    payload_id: Optional[str] = Field(default=None, description="Associated telemetry payload ID")
    alert_type: Optional[str] = Field(default=None, description="Type of alert (e.g. HIGH_CPU, HIGH_MEMORY)")
    metric_value: Optional[float] = Field(default=None, description="Observed metric value alias")
